#!/usr/bin/env python3
"""Assemble the unified manuscript and export HTML/PDF.

Usage
-----
  python3 scripts/assemble.py            # Markdown manuscript + index (always)
  python3 scripts/assemble.py --html     # + standalone HTML (needs pandoc)
  python3 scripts/assemble.py --pdf      # + PDF (needs pandoc and Chromium/Chrome)

Outputs (in exports/):
  speculators_desk_manuscript.md   unified manuscript in reading order
  speculators_desk.html            pandoc HTML with MathML (no network needed)
  speculators_desk.pdf             printed from the HTML by headless Chromium

Also writes textbook/INDEX.md (navigation: parts, chapters, status, problems, solutions).
Markdown is canonical; exports never block production of the Markdown source.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TB = ROOT / "textbook"
EXPORTS = ROOT / "exports"

PART_DIRS = ["frontmatter", "part_01_foundations", "part_02_macro", "part_03_cre", "part_04_cross_asset",
             "part_05_quantitative", "part_06_history", "part_07_decision_making", "appendices"]
PART_TITLES = {
    "frontmatter": "Front Matter",
    "part_01_foundations": "Part I — The Anatomy of Speculation",
    "part_02_macro": "Part II — Macroeconomic Intelligence",
    "part_03_cre": "Part III — Commercial Real Estate as a Speculative Asset",
    "part_04_cross_asset": "Part IV — The Other Speculative Markets",
    "part_05_quantitative": "Part V — Quantitative Trading and Risk",
    "part_06_history": "Part VI — Financial History as a Laboratory",
    "part_07_decision_making": "Part VII — The Investment Decision",
    "appendices": "Appendices",
}
STATUS_RE = re.compile(r"\*\*Status:\*\*\s*([^.\n(]+)")


def chapter_files() -> list[tuple[str, Path]]:
    out = []
    for d in PART_DIRS:
        for f in sorted((TB / d).glob("*.md")):
            out.append((d, f))
    return out


def status_of(text: str) -> str:
    m = STATUS_RE.search(text)
    return m.group(1).strip() if m else "—"


def first_heading(text: str, default: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return default


def build_index(files) -> str:
    lines = ["# The Speculator's Desk — Navigation Index", "",
             "Generated by `scripts/assemble.py`. Do not edit by hand.", ""]
    current = None
    for d, f in files:
        if d != current:
            lines += ["", f"## {PART_TITLES[d]}", "", "| File | Title | Status | Problems | Solutions |",
                      "|---|---|---|---|---|"]
            current = d
        text = f.read_text()
        m = re.match(r"ch(\d\d)", f.name)
        probs = sols = ""
        if m:
            q = ROOT / "problems/questions" / f"ch{m.group(1)}_problems.md"
            s = ROOT / "problems/solutions" / f"ch{m.group(1)}_solutions.md"
            probs = f"[problems](../problems/questions/{q.name})" if q.exists() else "—"
            sols = f"[solutions](../problems/solutions/{s.name})" if s.exists() else "—"
        lines.append(f"| [{f.name}]({d}/{f.name}) | {first_heading(text, f.stem)} | {status_of(text)} | {probs} | {sols} |")
    lines += ["", "## Cases", ""]
    for c in sorted((ROOT / "cases/hypothetical").glob("case_*")):
        mains = sorted(p for p in c.glob("case_*.md") if "rubric" not in p.name)
        if mains:
            lines.append(f"- [{first_heading(mains[0].read_text(), c.name)}](../cases/hypothetical/{c.name}/{mains[0].name})")
    for c in sorted((ROOT / "cases/historical").glob("*.md")):
        lines.append(f"- [{first_heading(c.read_text(), c.stem)}](../cases/historical/{c.name})")
    return "\n".join(lines) + "\n"


def assemble_markdown(files) -> str:
    parts = ["---", "title: \"The Speculator's Desk\"",
             "subtitle: \"Commercial Real Estate, Global Macro, Market Intelligence, and the Art of Decision-Making Under Uncertainty\"",
             "---", ""]
    current = None
    for d, f in files:
        if d != current:
            parts += ["", f"# {PART_TITLES[d]}" if d not in ("frontmatter",) else "", ""]
            current = d
        text = f.read_text()
        # demote headings one level inside parts so the part title is H1
        if d != "frontmatter":
            text = re.sub(r"^(#+) ", lambda m: "#" + m.group(1) + " ", text, flags=re.M)
        parts += [text, "", "\\newpage", ""]
    return "\n".join(parts)


def find_chromium() -> str | None:
    for cand in [os.environ.get("CHROMIUM"), "/opt/pw-browsers/chromium-1194/chrome-linux/chrome",
                 shutil.which("chromium"), shutil.which("chromium-browser"), shutil.which("google-chrome")]:
        if cand and Path(cand).exists():
            return cand
    for p in Path("/opt/pw-browsers").glob("chromium-*/chrome-linux/chrome"):
        return str(p)
    return None


CSS = """
body{max-width:52rem;margin:2rem auto;padding:0 1rem;font-family:Georgia,serif;line-height:1.5;color:#111}
table{border-collapse:collapse;margin:1rem 0;font-size:.92em}th,td{border:1px solid #999;padding:.25rem .5rem}
th{background:#eee}code,pre{font-size:.88em}pre{background:#f5f5f5;padding:.5rem;overflow-x:auto}
blockquote{border-left:3px solid #999;margin-left:0;padding-left:1rem;color:#333}
h1{page-break-before:always}
"""


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--html", action="store_true")
    ap.add_argument("--pdf", action="store_true")
    a = ap.parse_args(argv)

    files = chapter_files()
    EXPORTS.mkdir(exist_ok=True)
    (TB / "INDEX.md").write_text(build_index(files))
    md_path = EXPORTS / "speculators_desk_manuscript.md"
    md_path.write_text(assemble_markdown(files))
    print(f"wrote {md_path} ({len(files)} files)")
    print(f"wrote {TB / 'INDEX.md'}")

    if a.html or a.pdf:
        if not shutil.which("pandoc"):
            print("pandoc not found: skipping HTML/PDF (Markdown manuscript is complete)")
            return 0
        css = EXPORTS / "book.css"
        css.write_text(CSS)
        html = EXPORTS / "speculators_desk.html"
        subprocess.run(["pandoc", str(md_path), "-o", str(html), "--standalone", "--mathml", "--toc",
                        "--toc-depth=2", "--embed-resources", f"--css={css}",
                        "--metadata", "title=The Speculator's Desk"], check=True)
        print(f"wrote {html}")
        if a.pdf:
            chrome = find_chromium()
            if not chrome:
                print("Chromium not found: skipping PDF")
                return 0
            pdf = EXPORTS / "speculators_desk.pdf"
            subprocess.run([chrome, "--headless", "--no-sandbox", "--disable-gpu", "--no-pdf-header-footer",
                            f"--print-to-pdf={pdf}", html.resolve().as_uri()], check=True,
                           capture_output=True, timeout=600)
            print(f"wrote {pdf}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
